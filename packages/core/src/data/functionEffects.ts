/**
 * What calling each of tf's built-in functions (src/funclist.h) does besides returning a value,
 * for moving an expression to be evaluated a little earlier ("Extract to a local variable").
 *
 *  - "pure": the value depends only on the arguments, and nothing else changes.
 *  - "reads": the value also depends on tf's state (the screen, the input line, the worlds, the
 *    clock), but the call changes nothing. Evaluated a moment earlier, with nothing else run in
 *    between, it reads the same state, except that a clock (`time()`, `cputime()`, `idle()`) has
 *    moved on by that moment.
 *  - "effects": the call changes something: it prints, sends, reads input, runs a command or
 *    macro, opens, reads or writes a file, moves the input cursor, sets the regexp captures
 *    (`regmatch()`), the running macro's options (`getopts()`), the trigger line
 *    (`substitute()`), or advances the random sequence (`rand()`).
 *
 * funclist.h has a "pure" column of its own, but tf never reads it (expr.c's funccode() drops it),
 * and it marks `substitute()` pure, which rewrites the line a trigger matched; so the column is
 * not used here. A test checks that every function of the generated table is in this one.
 */
